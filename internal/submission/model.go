// Package submission receives source files and creates submission + judge
// run + judge job in one transaction (BACKEND_CONTEXT.md §7, §10, §19).
package submission

import "time"

// MaxSourceBytes is the upload limit for one .cpp file (BACKEND_CONTEXT.md §17).
const MaxSourceBytes = 64 << 10

// NewSubmission is what the repository needs to accept a submission.
type NewSubmission struct {
	StudentID  int64
	SessionID  int64
	ProblemID  int64
	SourcePath string // relative to DATA_DIR, generated by Storage
	ReceivedAt time.Time
}

// Result is the current judge run of a submission: the run whose
// problem_version equals problems.version and is not obsolete.
type Result struct {
	RunID          int64
	ProblemVersion int
	Status         string // queued, judging, completed, system_error
	Verdict        *string
	PassedTests    int
	TotalTests     int
	CompilerInfo   *string
	CompileOutput  *string
	SystemError    *string
	CreatedAt      time.Time
	StartedAt      *time.Time
	FinishedAt     *time.Time
}

type Submission struct {
	ID              int64
	SessionID       int64
	ExamID          int64
	TeacherID       int64 // owner of the exam, for permission checks
	ProblemID       int64
	ProblemCode     string
	ProblemVersion  int // problems.version now
	StudentID       int64
	StudentCode     string
	StudentFullname string
	SourcePath      string
	ReceivedAt      time.Time
	// Result is nil while no run exists at the current version (the problem
	// changed and requeueing has not created one yet).
	Result *Result
}

// Filter narrows a session's submission list.
type Filter struct {
	StudentID int64 // 0 = all
	ProblemID int64 // 0 = all
}

// TestResult is one row of submission_test_results for the current run.
type TestResult struct {
	TestCaseID      int64
	Verdict         string
	ExecutionTimeMs int
	MemoryUsedKB    *int64
}
